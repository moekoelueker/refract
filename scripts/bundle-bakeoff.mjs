#!/usr/bin/env node
/**
 * Bundle the bake-off's ES modules into one classic script.
 *
 * Why this exists: ES module imports are blocked by CORS over file://, so
 * opening a review page directly produced a silently blank screen. The library
 * source stays as ES modules (that is what will ship); this is a build artifact
 * for the review harness only, so the pages can be opened by double-clicking.
 *
 * Deliberately dependency-free and dumb: wrap each module in its own function
 * scope, rewrite `import`/`export` into registry reads and writes. Module
 * basenames are unique across the project, so they are the registry keys.
 *
 * Run: npm run bundle
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// dependency order, shallowest first
const CORE = [
  'packages/core/src/geometry.js',
  'packages/core/src/map.js',
  'packages/core/src/filter.js',
  'packages/core/src/capabilities.js',
  'packages/core/src/shader.js',
  'packages/core/src/approaches.js',
  'apps/bakeoff/lib/backdrops.js',
];

const BUNDLES = [
  {
    out: 'apps/bakeoff/lib/bundle.js',
    modules: [...CORE, 'apps/bakeoff/lib/board.js', 'apps/bakeoff/lib/page.js'],
    expose: 'window.mountPage = __M.page.mountPage;',
  },
  {
    out: 'apps/gallery/lib/bundle.js',
    modules: [...CORE, 'packages/ui/components.js', 'apps/gallery/lib/scenes.js', 'apps/gallery/lib/gallery.js'],
    expose: 'window.mountGallery = __M.gallery.mountGallery;',
  },
];

/** Rewrite one module's source into a registry factory. */
function transform(src, key) {
  const exports = new Set();
  let out = src;

  // import { a, b as c } from './x.js';  ->  const { a, b: c } = __M.x;
  out = out.replace(
    /^\s*import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm,
    (_, names, spec) => {
      const dep = basename(spec).replace(/\.js$/, '');
      const bind = names
        .split(',')
        .map((n) => n.trim())
        .filter(Boolean)
        .map((n) => {
          const m = n.match(/^(\S+)\s+as\s+(\S+)$/);
          return m ? `${m[1]}: ${m[2]}` : n;
        })
        .join(', ');
      return `const { ${bind} } = __M.${dep};`;
    },
  );

  // type-only or side-effect imports are not used here, but strip them anyway
  out = out.replace(/^\s*import\s+['"][^'"]+['"];?\s*$/gm, '');

  // export { a, b };  ->  record only
  out = out.replace(/^\s*export\s*\{([^}]+)\}\s*;?\s*$/gm, (_, names) => {
    for (const n of names.split(',')) {
      const t = n.trim().split(/\s+as\s+/).pop();
      if (t) exports.add(t);
    }
    return '';
  });

  // export const/let/function/async function/class NAME
  out = out.replace(
    /^\s*export\s+(async\s+function|function|const|let|var|class)\s+([A-Za-z0-9_$]+)/gm,
    (_, kind, name) => {
      exports.add(name);
      return `${kind} ${name}`;
    },
  );

  if (/^\s*export\s/m.test(out)) {
    throw new Error(`${key}: unhandled export form:\n` + out.match(/^\s*export\s.*$/m)[0]);
  }

  const ret = [...exports].map((n) => `${n}: ${n}`).join(', ');
  return `__M.${key} = (function () {\n${out}\nreturn { ${ret} };\n})();`;
}

for (const b of BUNDLES) {
  const parts = [
    '/* GENERATED by scripts/bundle-bakeoff.mjs — do not edit.',
    '   Source of truth is the ES modules under packages and apps.',
    '   Regenerate with: npm run bundle */',
    '(function () {',
    '"use strict";',
    'var __M = {};',
  ];
  for (const rel of b.modules) {
    const key = basename(rel).replace(/\.js$/, '');
    parts.push(`/* ── ${rel} ───────────────────────────────────── */`);
    parts.push(transform(readFileSync(join(ROOT, rel), 'utf8'), key));
  }
  parts.push(b.expose);
  parts.push('})();');
  const outPath = join(ROOT, b.out);
  writeFileSync(outPath, parts.join('\n') + '\n');
  console.log(`bundled ${b.modules.length} modules -> ${b.out} (${(readFileSync(outPath, 'utf8').length / 1024).toFixed(1)} KB)`);
}
